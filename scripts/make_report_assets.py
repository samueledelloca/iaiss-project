#!/usr/bin/env python3
"""Generate LaTeX value-macros and tables from the actual results.

Keeps every number in the report identical to the computed results (no manual
transcription). Writes reports/generated_values.tex and reports/tables/*.tex.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from c9n2a import datasets, paths  # noqa: E402

R = paths.RESULTS
REPORTS = paths.REPORTS
(REPORTS / "tables").mkdir(parents=True, exist_ok=True)


def load(p):
    return json.loads(Path(p).read_text())


def esc(s: str) -> str:
    s = (str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
         .replace(">=", r"GEQ").replace("<=", r"LEQ").replace("->", r"TO"))
    s = s.replace(">", r"$>$").replace("<", r"$<$")
    s = s.replace("GEQ", r"$\geq$").replace("LEQ", r"$\leq$").replace("TO", r"$\to$")
    return s.replace("rho", r"$\rho$")


def fnum(x, sig=3):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return str(x)
    if x == 0:
        return "0"
    if abs(x) < 1e-3 or abs(x) >= 1e4:
        return f"\\num{{{x:.2e}}}"
    return f"{x:.3g}"


def main() -> None:
    repro = load(R / "analyses" / "reproductions.json")
    obs = load(R / "discovery" / "observations.json")
    contra = load(R / "discovery" / "contradictions.json")
    sci = load(paths.EVALUATION / "scientific.json")
    ai = load(paths.EVALUATION / "ai.json")

    # ---- macros ----
    def pval(aid):
        a = next(x for x in repro if x["id"] == aid)
        return a["stats"]["p_value"]
    macros = {
        "ReproTotalP": fnum(pval("repro_fig2_C9orf72_Total")),
        "ReproILfiveP": fnum(pval("repro_fig2_C9orf72_IL5")),
        "ReproILtenP": fnum(pval("repro_fig2_C9orf72_IL10")),
        "ReproIFNgP": fnum(pval("repro_fig2_C9orf72_IFNg")),
        "NumObservations": str(len(obs)),
        "NumQuestions": str(len(load(R / 'discovery' / 'questions.json'))),
        "FidelityMaxDiff": fnum(sci["reproducibility"]["reported_pvalue_fidelity"]["max_abs_diff"]),
        "GroundingRate": f"{ai['hallucination']['grounding_rate']:.2f}",
        "ToolAccuracy": f"{ai['tool_use_accuracy']['accuracy']:.2f}",
        "NullsRejected": f"{ai['false_hypothesis_rejection']['correctly_rejected']}/{ai['false_hypothesis_rejection']['n']}",
        "SpatialPerm": fnum(next(x for x in load(R / 'analyses' / 'exploratory.json')
                                 if x['id'] == 'explore_spatial')['stats']['perm_p']),
    }
    mpath = paths.RESULTS / "model" / "immunogenicity_metrics.json"
    if mpath.exists():
        m = load(mpath)
        macros["ModelBaselineAUC"] = f"{m['baseline_auc_mean']:.2f}"
        macros["ModelGBAUC"] = f"{m['cv_auc_mean']:.2f}"
        macros["ModelN"] = str(m["n"])
        macros["ModelPos"] = str(m["n_positive"])
    (REPORTS / "generated_values.tex").write_text(
        "% auto-generated by scripts/make_report_assets.py\n" +
        "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")

    # ---- Table: reproduction of claims ----
    rows = []
    for a in repro:
        p = a["stats"].get("p_value") if isinstance(a["stats"], dict) else None
        rows.append(f"{esc(a['question'][:52])} & {fnum(p) if p is not None else '--'} & "
                    f"{esc((a['reproduces'] or '')[:34])} \\\\")
    (REPORTS / "tables" / "reproduction.tex").write_text(
        "\\begin{tabular}{p{6.2cm}cp{4.3cm}}\n\\toprule\n"
        "Question & $p$ & Paper claim reproduced \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: novel observations ----
    rows = [f"{o['id']} & {esc(o['observation'][:108])} & {esc(o['relation_to_paper'].split()[0])} \\\\"
            for o in obs]
    (REPORTS / "tables" / "observations.tex").write_text(
        "\\begin{tabular}{lp{10.2cm}l}\n\\toprule\nID & Verified novel observation & vs paper \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: top epitopes ----
    pep = datasets.load("si_table1_peptide_screen").nlargest(8, "avg_magnitude")
    rows = [f"{int(r.epitope_num)} & {r.residues} & {r.sequence} & {int(r.responders)}/{int(r.tested)} & "
            f"{r.avg_magnitude:.0f} & {'' if r.n_predicted_hla_bound!=r.n_predicted_hla_bound else int(r.n_predicted_hla_bound)} \\\\"
            for r in pep.itertuples()]
    (REPORTS / "tables" / "epitopes.tex").write_text(
        "\\begin{tabular}{lllccc}\n\\toprule\n\\# & Residues & Sequence & Resp./Tested & Mag. & HLA \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: HLA restrictions (Table 2) ----
    hla = datasets.load("table2_hla_restrictions")
    rows = [" & ".join(esc(str(v)) for v in r) + r" \\" for r in hla.values.tolist()]
    (REPORTS / "tables" / "hla.tex").write_text(
        "\\begin{tabular}{llcc}\n\\toprule\n" + " & ".join(esc(c) for c in hla.columns) +
        " \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: evaluation metrics ----
    ev = [("Paper claims reproduced",
           f"{sci['reproducibility']['paper_claims_reproduced']}/{sci['reproducibility']['n_reproduction_questions']}"),
          ("Reported-$p$ fidelity (max $|\\Delta p|$)", fnum(sci['reproducibility']['reported_pvalue_fidelity']['max_abs_diff'])),
          ("Verified novel observations", str(sci['novelty']['verified_novel_observations'])),
          ("Grounding rate (no hallucinated numbers)", f"{ai['hallucination']['grounding_rate']:.2f}"),
          ("Tool-use accuracy", f"{ai['tool_use_accuracy']['accuracy']:.2f}"),
          ("Deterministic reproduction", str(ai['reproducibility']['deterministic'])),
          ("Planted nulls correctly rejected", macros["NullsRejected"]),
          ("Questions self-flagged with caveats", str(ai['self_error_detection']['questions_self_flagged']))]
    rows = [f"{esc(k)} & {v} \\\\" for k, v in ev]
    (REPORTS / "tables" / "evaluation.tex").write_text(
        "\\begin{tabular}{p{8.5cm}l}\n\\toprule\nMetric & Value \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: agent roster ----
    specs = load(paths.AGENTS / "registry.json")
    lay = {3: "Scientific", 4: "Discovery", 5: "PI"}
    rows = [f"{s['name'].replace('_',' ')} & {lay.get(s['layer'],s['layer'])} & {esc(s['role'][:58])} \\\\"
            for s in specs]
    (REPORTS / "tables" / "agents.tex").write_text(
        "\\begin{tabular}{p{3.6cm}lp{7.6cm}}\n\\toprule\nAgent & Layer & Role \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: tool catalogue ----
    sys.path.insert(0, str(paths.ROOT / "src"))
    from c9n2a import tools as T  # noqa: E402
    rows = [f"\\texttt{{{n.replace('_', chr(92)+'_')}}} & {esc(t.description[:66])} \\\\"
            for n, t in T.TOOLS.items()]
    (REPORTS / "tables" / "tools.tex").write_text(
        "\\begin{tabular}{p{4.6cm}p{9.0cm}}\n\\toprule\nTool & Purpose \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: contradictions / limitations ----
    def short_type(t):
        t = str(t)
        return "caveat" if "caveat" in t else ("limitation" if "limit" in t else
               ("uncertainty" if "uncert" in t else t.split()[0]))
    rows = [f"{c['id']} & {short_type(c['type'])} & {esc(c['item'][:140])} \\\\" for c in contra]
    (REPORTS / "tables" / "contradictions.tex").write_text(
        "\\begin{tabular}{llp{11.0cm}}\n\\toprule\nID & Type & Item \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: all 24 questions ----
    qs = load(R / "discovery" / "questions.json")
    rows = [f"{q['id']} & {esc(q['kind'])} & {esc(q['question'][:70])} & "
            f"{esc(q['relation_to_paper'].split()[0])} \\\\" for q in qs]
    (REPORTS / "tables" / "questions.tex").write_text(
        "\\begin{tabular}{llp{8.3cm}l}\n\\toprule\nID & Kind & Question & vs paper \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: datasets ----
    grain = {"fig2_fluorospot_responses": "per-donor FluoroSpot magnitude",
             "fig1_tcell_subsets": "per-donor subset \\%", "fig3_epitopes": "per-epitope",
             "fig4_mutation_survival": "per-donor by stratum", "si_table1_peptide_screen": "per-peptide (100)",
             "si_table2_hla_typing": "per-donor x locus x allele", "reported_pvalues": "authors' p-values",
             "edfig2_ifng_il5_ratio": "per-donor cytokine", "edfig4_cd4_cd8": "per-donor CD4/CD8",
             "edfig5_immunogenicity_hla": "immunogenicity vs HLA", "edfig6_clinical_correlates": "per-donor clinical",
             "table1_epitopes_ge3donors": "epitopes >=3 donors", "table2_hla_restrictions": "HLA restrictions"}
    rows = []
    for name in sorted(grain):
        try:
            df = datasets.load(name)
            rows.append(f"\\texttt{{{name.replace('_', chr(92)+'_')}}} & {len(df)} & {esc(grain[name])} \\\\")
        except Exception:
            pass
    (REPORTS / "tables" / "datasets.tex").write_text(
        "\\begin{tabular}{p{6.0cm}rp{5.6cm}}\n\\toprule\nDataset & Rows & Grain \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # references.bib is built separately by scripts/enrich_references.py (Crossref-verified).
    print("Wrote generated_values.tex and the result tables.")


if __name__ == "__main__":
    main()
